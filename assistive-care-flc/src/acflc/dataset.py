"""The (x_i, y_i) training examples for Part 2.

Provenance -- read this before quoting any number from it
---------------------------------------------------------
**This data is synthetic. It is not logged from a real flat, a real resident
or a real occupational therapist, and nothing derived from it is evidence
about real occupants.**

Part 2 asks for the membership functions to be tuned "against a dataset of n
input-output examples". No such dataset exists publicly for assistive-care
environmental control, and collecting one would need ethical approval and
residents. The examples here are therefore generated from an explicitly stated
reference policy: a smooth analytical comfort model standing in for the
settings a therapist would prescribe, plus Gaussian noise standing in for the
disagreement between annotators.

The substitution is declared here, in the report, and in the results file. It
is a stand-in for real data, and the GA's measured improvement should be read
as "the search can recover a known target", not as "the tuned controller is
better for real residents".

Why the reference policy is not itself a fuzzy system
-----------------------------------------------------
The target is deliberately a *different functional form* from the controller:
saturating linear ramps, not a union of clipped fuzzy sets. If the target were
generated by a Mamdani system with the same rule base, the GA could in
principle drive the error to zero and the exercise would only show that the
encoding can represent its own output. Fitting a genuinely different shape is
the harder and more honest test, and it means residual error at convergence is
expected rather than a sign of failure.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

# ------------------------------------------------------- the reference policy

#: Neutral comfort setpoint in degrees C for a resting occupant at preference 0.
SETPOINT_BASE = 23.5
#: Degrees the setpoint falls per unit of activity index. A resting occupant
#: with reduced metabolic heat wants a warmer room than an active one.
SETPOINT_PER_ACTIVITY = -0.45
#: Degrees the setpoint moves per unit of the resident's preference dial.
SETPOINT_PER_PREFERENCE = 0.60
#: Proportional gain, % of plant capacity per degree of setpoint error.
HVAC_GAIN = 14.0
#: Authority limit of the modelled plant.
HVAC_LIMIT = 85.0

#: Illuminance the task needs, as % lamp output, at zero activity...
LAMP_BASE = 25.0
#: ...and its increase per unit of activity index.
LAMP_PER_ACTIVITY = 6.5
#: Fraction of the task requirement that arriving daylight displaces.
DAYLIGHT_CREDIT = 0.85
#: The fall-risk floor: orientation lighting is never fully extinguished.
LAMP_FLOOR = 8.0
LAMP_CEILING = 95.0


def reference_policy(X: np.ndarray) -> np.ndarray:
    """The target control action for inputs X, shaped (N, 4) -> (N, 2).

    Columns of X are room_temp, activity, daylight, preference, matching the
    controller's `input_names` order.

        setpoint = 23.5 - 0.45 * activity + 0.60 * preference
        hvac     = clip( 14.0 * (setpoint - room_temp), -85, +85 )

        need     = 25.0 + 6.5 * activity
        dimmer   = clip( need - 0.85 * daylight, 8, 95 )

    Both are deliberately simple and monotone. The interesting question is not
    whether this policy is the true comfort function -- it is not -- but
    whether a 648-bit search can bend a 54-rule fuzzy controller onto it.
    """
    X = np.atleast_2d(np.asarray(X, dtype=float))
    room_temp, activity, daylight, preference = X.T

    setpoint = (SETPOINT_BASE
                + SETPOINT_PER_ACTIVITY * activity
                + SETPOINT_PER_PREFERENCE * preference)
    hvac = np.clip(HVAC_GAIN * (setpoint - room_temp), -HVAC_LIMIT, HVAC_LIMIT)

    need = LAMP_BASE + LAMP_PER_ACTIVITY * activity
    dimmer = np.clip(need - DAYLIGHT_CREDIT * daylight, LAMP_FLOOR, LAMP_CEILING)

    return np.column_stack([hvac, dimmer])


@dataclass
class Dataset:
    """A train/test split of synthetic input-output examples."""

    X_train: np.ndarray
    y_train: np.ndarray
    X_test: np.ndarray
    y_test: np.ndarray
    noise_sd: np.ndarray
    seed: int

    @property
    def n_train(self) -> int:
        return len(self.X_train)

    @property
    def n_test(self) -> int:
        return len(self.X_test)

    def describe(self) -> dict:
        return {
            "provenance": "SYNTHETIC - generated from acflc.dataset.reference_policy, "
                          "not logged from real occupants",
            "n_train": self.n_train,
            "n_test": self.n_test,
            "noise_sd": [float(v) for v in self.noise_sd],
            "seed": self.seed,
        }


def make_dataset(flc, n=400, test_fraction=0.3, noise_pct=3.0, seed=20260906):
    """Sample the input space uniformly and label it with the reference policy.

    Inputs are drawn uniformly rather than from a plausible occupancy
    distribution on purpose: a GA fitted only to the states a flat usually
    occupies would leave the membership functions covering rare states -- a
    heating failure, a heatwave -- entirely untuned, and those are the states
    where the controller matters most.

    `noise_pct` is a percentage of each output's span, applied as Gaussian
    noise. It represents annotator disagreement, and it also stops the GA from
    chasing digits that would not survive contact with real data.

    The split is held out strictly: `X_test` is never seen during evolution,
    so the reported test error says whether the tuning generalised or merely
    memorised the training draw.
    """
    rng = np.random.default_rng(seed)
    lo = np.array([flc.inputs[n_].lo for n_ in flc.input_names])
    hi = np.array([flc.inputs[n_].hi for n_ in flc.input_names])
    X = rng.uniform(lo, hi, size=(n, len(lo)))

    y = reference_policy(X)
    spans = np.array([flc.outputs[n_].hi - flc.outputs[n_].lo
                      for n_ in flc.output_names])
    noise_sd = spans * noise_pct / 100.0
    y = y + rng.normal(0.0, noise_sd, size=y.shape)

    n_test = int(round(n * test_fraction))
    idx = rng.permutation(n)
    te, tr = idx[:n_test], idx[n_test:]
    return Dataset(X[tr], y[tr], X[te], y[te], noise_sd, seed)


def normalised_rmse(y_true, y_pred, spans):
    """RMSE per output, divided by that output's span, then averaged.

    The two outputs live on different scales -- HVAC spans 200 units of signed
    capacity, the dimmer 100 units of percent. Averaging raw squared error
    would let HVAC dominate the fitness roughly four to one and the lighting
    membership functions would go effectively untuned. Normalising by span
    makes a 1% error in each count the same, which is the intended trade.

    NaN predictions (an input that activates no rule) are charged the full
    span as error rather than dropped, so a GA cannot improve its score by
    evolving a controller with holes in it.
    """
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)
    spans = np.asarray(spans, dtype=float)

    err = y_pred - y_true
    bad = ~np.isfinite(err)
    err = np.where(bad, spans[None, :], err)
    per_output = np.sqrt(np.mean(err ** 2, axis=0)) / spans
    return float(per_output.mean()), per_output
